-- SGT - Sistema de Gestão do Tempo
-- Esquema do banco de dados (PostgreSQL 16) da Sprint 3: US01, US02 e US03.
--
-- Este arquivo é uma cópia legível do que a migration do EF Core cria
-- (GestaoTempo.Api/Data/Migrations). Serve para entrega e consulta.
--
-- Como usar: rode em um banco VAZIO, por exemplo:
--   createdb -U postgres sgt
--   psql -U postgres -d sgt -f docs/banco.sql
--
-- Para rodar a API, não precisa deste arquivo: ao subir em Development ela
-- cria as tabelas sozinha. Não rode este script em um banco que a API já criou.

-- Texto que não diferencia maiúsculas de minúsculas (usado no e-mail).
CREATE EXTENSION IF NOT EXISTS citext;

-- US01 - Cadastrar conta / US02 - Entrar e sair do sistema
CREATE TABLE usuario (
    id_usuario  integer GENERATED BY DEFAULT AS IDENTITY,
    nome        varchar(100) NOT NULL,
    email       citext       NOT NULL,   -- "Joao@x.com" e "joao@x.com" são o mesmo e-mail
    senha_hash  varchar(255) NOT NULL,   -- nunca a senha em texto puro
    criado_em   timestamptz  NOT NULL,
    CONSTRAINT "PK_usuario" PRIMARY KEY (id_usuario)
);

-- E-mail único: não aceita conta com e-mail já cadastrado (US01).
CREATE UNIQUE INDEX "IX_usuario_email" ON usuario (email);

-- Categorias de cada usuário. A conta nova recebe as 5 padrão:
-- Trabalho, Estudos, Pessoal, Familia e Relacionamentos (US01).
CREATE TABLE categoria (
    id_categoria integer GENERATED BY DEFAULT AS IDENTITY,
    id_usuario   integer     NOT NULL,
    nome         varchar(50) NOT NULL,
    cor          varchar(7)  NOT NULL,   -- ex.: #FF5733
    padrao       boolean     NOT NULL,   -- true nas 5 categorias padrão
    CONSTRAINT "PK_categoria" PRIMARY KEY (id_categoria),
    CONSTRAINT "FK_categoria_usuario_id_usuario"
        FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE
);

-- Um usuário não pode ter duas categorias com o mesmo nome.
-- (Também serve para buscar as categorias de um usuário.)
CREATE UNIQUE INDEX "IX_categoria_id_usuario_nome" ON categoria (id_usuario, nome);

-- US03 - Cadastrar tarefa
CREATE TABLE tarefa (
    id_tarefa      integer GENERATED BY DEFAULT AS IDENTITY,
    id_usuario     integer      NOT NULL,   -- dono da tarefa (cada usuário vê só as suas)
    id_categoria   integer      NOT NULL,
    titulo         varchar(150) NOT NULL,   -- obrigatório
    descricao      text,
    prazo          timestamptz  NOT NULL,   -- obrigatório; não pode ser data que já passou (regra da classe Tarefa)
    estimativa_min integer      NOT NULL,   -- tempo estimado em minutos, obrigatório
    tempo_real_min integer      NOT NULL,   -- começa em 0
    criticidade    varchar(20)  NOT NULL,   -- Baixa, Media, Alta, Critica
    complexidade   varchar(20)  NOT NULL,   -- Baixa, Media, Alta
    prioridade     varchar(30)  NOT NULL,   -- Urgente_Importante, Importante_NaoUrgente,
                                            -- Urgente_NaoImportante, NaoUrgente_NaoImportante
    status         varchar(20)  NOT NULL,   -- Pendente, EmAndamento, Concluida, Cancelada
    criada_em      timestamptz  NOT NULL,
    concluida_em   timestamptz,
    CONSTRAINT "PK_tarefa" PRIMARY KEY (id_tarefa),

    -- Regras que o banco também garante (a API valida antes, nas classes do Domain).
    CONSTRAINT "CK_tarefa_estimativa_positiva"       CHECK (estimativa_min > 0),
    CONSTRAINT "CK_tarefa_titulo_preenchido"         CHECK (char_length(btrim(titulo)) > 0),
    CONSTRAINT "CK_tarefa_tempo_real_nao_negativo"   CHECK (tempo_real_min >= 0),
    CONSTRAINT "CK_tarefa_status_valido"             CHECK (status IN ('Pendente', 'EmAndamento', 'Concluida', 'Cancelada')),
    CONSTRAINT "CK_tarefa_criticidade_valida"        CHECK (criticidade IN ('Baixa', 'Media', 'Alta', 'Critica')),
    CONSTRAINT "CK_tarefa_complexidade_valida"       CHECK (complexidade IN ('Baixa', 'Media', 'Alta')),
    CONSTRAINT "CK_tarefa_prioridade_valida"         CHECK (prioridade IN ('Urgente_Importante', 'Importante_NaoUrgente',
                                                                           'Urgente_NaoImportante', 'NaoUrgente_NaoImportante')),

    CONSTRAINT "FK_tarefa_usuario_id_usuario"
        FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT "FK_tarefa_categoria_id_categoria"
        FOREIGN KEY (id_categoria) REFERENCES categoria (id_categoria) ON DELETE RESTRICT
);

-- Listar e filtrar as tarefas de um usuário por status ou por prazo.
CREATE INDEX "IX_tarefa_id_usuario_status" ON tarefa (id_usuario, status);
CREATE INDEX "IX_tarefa_id_usuario_prazo"  ON tarefa (id_usuario, prazo);
CREATE INDEX "IX_tarefa_id_categoria"      ON tarefa (id_categoria);
